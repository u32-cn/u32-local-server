#!/usr/bin/env node

// SEA 打包脚本：把 u32-local-server 打成单文件可执行程序（不依赖目标机器安装 Node）
// 用法：node scripts/build-sea.js [--out dist]
// 原理（Node 22 官方 SEA，https://nodejs.org/api/single-executable-applications.html）：
//   1. node --experimental-sea-config 生成 blob（含入口脚本 + assets 资源）
//   2. 拷贝 node 运行时二进制
//   3. postject 把 blob 注入二进制（NODE_SEA_BLOB fuse）
// 资源约定：public/、docs/ 全量嵌入；入口 bundle 顶部注入 process.env.U32_LS_SEA 标记。
// 注意：SEA 不支持交叉编译，Windows 的 exe 只能在 Windows 上打，Linux/macOS 同理。

const fs = require('fs')
const path = require('path')
const os = require('os')
const { execFileSync } = require('child_process')

const ROOT = path.resolve(__dirname, '..')
const OUT_DIR = process.argv.includes('--out')
  ? path.resolve(ROOT, process.argv[process.argv.indexOf('--out') + 1])
  : path.join(ROOT, 'dist')
const PKG = require(path.join(ROOT, 'package.json'))

// ---- 收集嵌入资源 ----
const ASSET_DIRS = ['public', 'docs', 'src/picker', 'resources']
const ASSET_FILES = ['scripts/tray.ps1']
const assets = {}
for (const dir of ASSET_DIRS) {
  const abs = path.join(ROOT, dir)
  if (!fs.existsSync(abs)) continue
  for (const p of walk(abs)) {
    // key 统一 / 分隔，与 src/sea-assets.js 的 assetKey() 对齐
    const key = 'assets/' + path.relative(ROOT, p).replace(/\\/g, '/')
    assets[key] = path.relative(ROOT, p).replace(/\\/g, '/')
  }
}
for (const file of ASSET_FILES) {
  const abs = path.join(ROOT, file)
  if (fs.existsSync(abs)) {
    const key = 'assets/' + file.replace(/\\/g, '/')
    assets[key] = file
  }
}

function walk(dir) {
  const out = []
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name)
    if (fs.statSync(p).isDirectory()) out.push(...walk(p))
    else out.push(p)
  }
  return out
}

// ---- 生成入口 bundle ----
// SEA 要求单文件入口脚本；这里把 src/**（含 require 相对引用）合并。
// 项目零依赖、全 CommonJS、无动态 require，可以安全做朴素的模块拼接：
//   用 mini bundler 方式：按 require 图拓扑合并，保持 require(...) 语义。
// 更简单可靠的方案：SEA 支持 require() 内置模块，但不支持 require 相对文件——
// 所以必须合并。逐文件把 module.exports/require 换成注册表实现。
function buildBundle() {
  const entry = path.join(ROOT, 'src', 'index.js')
  const modules = {} // relPath -> code
  const order = []
  const binHeader = {}

  function resolveFrom(fromFile, reqPath) {
    if (!reqPath.startsWith('.')) return null // 内置模块，运行时原生 require
    if (reqPath.endsWith('package.json')) return 'package.json'
    // 解析顺序与 Node 一致：先试 <spec>.js 文件，再试 <spec>/index.js
    let p = path.resolve(path.dirname(fromFile), reqPath)
    const candidates = [p + '.js', path.join(p, 'index.js'), p]
    for (const c of candidates) {
      try {
        if (fs.statSync(c).isFile()) return path.relative(ROOT, c).replace(/\\/g, '/')
      } catch {}
    }
    throw new Error('Cannot resolve require ' + reqPath + ' from ' + fromFile)
  }

  function visit(relPath) {
    if (relPath === 'package.json') return // 特殊处理：bundle 尾部直接内联 JSON
    if (modules[relPath]) return
    const abs = path.join(ROOT, relPath)
    let code = fs.readFileSync(abs, 'utf8')
    // 顶层shebang去掉
    code = code.replace(/^#![^\n]*\n/, '')
    // 收集并重写 require 调用：require('./x') -> require("<module-id>")
    code = code.replace(/require\(\s*(['"])([^'"]+)\1\s*\)/g, (m, q, spec) => {
      const id = resolveFrom(relPath, spec)
      if (!id) return m // 内置模块原样
      visit(id)
      return `require(${JSON.stringify(id)})`
    })
    // package.json 引用改从 binHeader 取（SEA 下磁盘没有 package.json）
    if (relPath !== 'package.json') {
      code = code.replace(/require\((['"])(\.\.\/)?package\.json\1\)/g, 'require("package.json")')
    }
    modules[relPath] = code
    order.push(relPath)
  }

  // 递归扫 src 下所有 js（有的模块被动态引用也一并打包）
  // 排除 src/picker/client/：浏览器端 ES 模块，作为静态资源随 assets 嵌入，不参与 Node bundle
  for (const p of walk(path.join(ROOT, 'src'))) {
    const rel = path.relative(ROOT, p).replace(/\\/g, '/')
    if (p.endsWith('.js') && !rel.startsWith('src/picker/client/')) visit(rel)
  }
  binHeader['package.json'] = JSON.stringify(PKG, null, 2)

  const parts = []
  parts.push('// ===== SEA bundle auto-generated by scripts/build-sea.js =====')
  parts.push('process.env.U32_LS_SEA = "1"')
  parts.push('const __MODULES = {')
  for (const id of order) {
    parts.push(`${JSON.stringify(id)}: function(module, exports, require, __filename, __dirname) {\n'use strict';\n${modules[id]}\n},`)
  }
  parts.push(`${JSON.stringify('package.json')}: function(module, exports) { module.exports = ${binHeader['package.json']} },`)
  parts.push('};')
  parts.push(`
const __path = require('path');
const __rootDir = __path.dirname(process.execPath); // SEA 模式：包根视作 exe 所在目录（config 等运行时文件仍落用户目录）
const __CACHE = Object.create(null); // 模块登记本：对齐 Node require 缓存。缺失时同一模块被 require 多次会实例化多份，
                                     // 有状态的模块（如 artifacts 的 cfg）只有第一份被 init，其余读到 null。
function __require(id) {
  if (Object.prototype.hasOwnProperty.call(__MODULES, id)) {
    if (__CACHE[id]) return __CACHE[id].exports; // 已登记 → 返回同一份，不再重新执行
    const fn = __MODULES[id];
    const module = { exports: {} };
    __CACHE[id] = module; // 先登记再执行：循环依赖时第二次 require 拿到半成品，不会重复执行
    const dir = __path.posix.dirname(id);
    fn(module, module.exports, __require, id, dir);
    return module.exports;
  }
  return require(id); // 内置模块（node:sea / fs / path ...）
}
__require(${JSON.stringify('src/index.js')});
`)
  return parts.join('\n')
}

// ---- 主流程 ----
async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true })
  const bundlePath = path.join(OUT_DIR, 'sea-entry.cjs')
  const seaConfigPath = path.join(OUT_DIR, 'sea-config.json')
  const blobPath = path.join(OUT_DIR, 'sea-prep.blob')
  const exeName = process.platform === 'win32' ? 'u32-ls.exe' : 'u32-ls'
  const exePath = path.join(OUT_DIR, exeName)

  console.log('[1/5] Collect assets:', Object.keys(assets).length, 'files')

  const bundle = buildBundle()
  fs.writeFileSync(bundlePath, bundle)
  console.log('[2/5] Bundle written:', bundlePath, (fs.statSync(bundlePath).size / 1024).toFixed(0) + 'KB')

  const seaConfig = {
    main: path.relative(process.cwd(), bundlePath).replace(/\\/g, '/'),
    output: path.relative(process.cwd(), blobPath).replace(/\\/g, '/'),
    disableExperimentalSEAWarning: true,
    useSnapshot: false,
    useCodeCache: true,
    assets: {},
  }
  for (const [key, diskPath] of Object.entries(assets)) {
    seaConfig.assets[key] = diskPath
  }
  fs.writeFileSync(seaConfigPath, JSON.stringify(seaConfig, null, 2))

  console.log('[3/5] Generating SEA blob...')
  execFileSync(process.execPath, ['--experimental-sea-config', seaConfigPath], { stdio: 'inherit', cwd: ROOT })

  console.log('[4/5] Copying node runtime...')
  fs.copyFileSync(process.execPath, exePath)
  if (process.platform !== 'win32') fs.chmodSync(exePath, 0o755)

  console.log('[5/5] Injecting blob (postject)...')
  const { inject } = require('postject')
  const blob = fs.readFileSync(blobPath)
  // Windows：资源名 NODE_SEA_BLOB（postject 内部会转大写），并写 NODE_SEA_BLOB fuse
  // 官方 CLI 对 win32 额外传 machoSegmentName 仅 mac 用；fuse 由 sentinelFuse 默认值处理
  await inject(exePath, 'NODE_SEA_BLOB', blob, {
    overwrite: true,
    // Node 22 运行时里的 fuse 格式为 NODE_SEA_FUSE_<hash>:0（实测），
    // postject 会把它改成 :1 表示已注入；默认 POSTJECT_SENTINEL_* 不适用。
    sentinelFuse: 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2',
  })

  const size = (fs.statSync(exePath).size / 1024 / 1024).toFixed(1)
  console.log('DONE:', exePath, size + 'MB')
}

main().catch(err => { console.error(err); process.exit(1) })
