// Browser Bridge（浏览器桥）：AI 与浏览器页面之间的透明转发层
// 页面 register 拿 appInstanceId → 循环 poll 蹲守 → 执行业务 → POST reply 回包
// AI 通过 GET /pages、/apps 查名册，POST /send/<id> 发消息并同步等回包
// 身份模型：appId（一种 App 一个）+ appInstanceId（一个页面实例一个，页面侧生成，取代 pageId）
// 服务器只做消息透传，不解释业务语义；全部状态在内存，不入盘

const crypto = require('crypto')
const fs = require('fs')
const logger = require('./logger')
const artifacts = require('./artifacts')

const POLL_TIMEOUT_MS = 25000       // poll 挂起上限，到点返回空数组（空心跳）
const SEND_DEFAULT_TIMEOUT_MS = 30000 // /send 默认等回包时长，到点 504
const OFFLINE_THRESHOLD_MS = 60000  // lastSeen 超过此值且无挂起 poll → 视为离线
const MAX_BODY_BYTES = 1024 * 1024

// appInstanceId → { appId, url, title, help, connectedAt, lastSeen }
const pages = new Map()
// appInstanceId → { res, timer }  挂起的 poll
const pollPending = new Map()
// appInstanceId → [ { id, type, payload } ]  待下发消息队列
const outbox = new Map()
// msgId → { res, timer, appInstanceId }  挂起的 /send
const sendPending = new Map()

function sendJson(res, code, obj) {
  const body = JSON.stringify(obj)
  res.writeHead(code, {
    'Content-Type': 'application/json; charset=utf-8',
    'Cache-Control': 'no-store',
    'access-control-allow-origin': '*',
    'access-control-allow-methods': 'GET, POST, OPTIONS',
    'access-control-allow-headers': '*',
  })
  res.end(body)
}

function readJsonBody(req) {
  return new Promise((resolve, reject) => {
    let size = 0
    const chunks = []
    req.on('data', (chunk) => {
      size += chunk.length
      if (size > MAX_BODY_BYTES) {
        reject(new Error('body too large'))
        req.destroy()
        return
      }
      chunks.push(chunk)
    })
    req.on('end', () => {
      if (chunks.length === 0) return resolve({})
      try {
        resolve(JSON.parse(Buffer.concat(chunks).toString('utf8')))
      } catch (e) {
        reject(new Error('invalid JSON'))
      }
    })
    req.on('error', reject)
  })
}

// 读 body 且要求 JSON 合法、body 是对象；失败时已回复 400
async function readJsonBodyOr400(req, res) {
  try {
    const body = await readJsonBody(req)
    if (typeof body !== 'object' || body === null || Array.isArray(body)) {
      sendJson(res, 400, { ok: false, error: 'body must be a JSON object' })
      return null
    }
    return body
  } catch (e) {
    sendJson(res, 400, { ok: false, error: e.message })
    return null
  }
}

// 兑现挂起的 poll 并下发积压消息；无挂起则消息留在 outbox 等下次 poll
function deliverToPoll(id) {
  const pending = pollPending.get(id)
  if (!pending) return false
  const messages = outbox.get(id) || []
  outbox.delete(id)
  clearTimeout(pending.timer)
  pollPending.delete(id)
  sendJson(pending.res, 200, { messages })
  return true
}

// 兑现挂起的 /send（页面回包；error 时仍透传 payload，如 runScript 异常回包附已捕获 console）
function settleSend(msgId, body) {
  const pending = sendPending.get(msgId)
  if (!pending) return false
  clearTimeout(pending.timer)
  sendPending.delete(msgId)
  if (body.error !== undefined && body.error !== null) {
    const reply = { id: msgId, error: body.error }
    if (body.payload !== undefined) reply.payload = body.payload
    sendJson(pending.res, 200, reply)
  } else {
    sendJson(pending.res, 200, { id: msgId, payload: body.payload })
  }
  return true
}

// 移除实例：出名册、清积压消息、断开挂起 poll
function dropPage(id) {
  pages.delete(id)
  outbox.delete(id)
  const pending = pollPending.get(id)
  if (pending) {
    clearTimeout(pending.timer)
    pollPending.delete(id)
    try { pending.res.destroy() } catch (e) {}
  }
}

// 惰性下线判定：超过阈值且无挂起 poll → 移出名册；返回是否仍在线
function checkAlive(id, now) {
  const page = pages.get(id)
  if (!page) return false
  if (!pollPending.has(id) && now - page.lastSeen > OFFLINE_THRESHOLD_MS) {
    logger.info(`[BRIDGE] Instance offline (stale): ${id} (appId=${page.appId})\n`)
    dropPage(id)
    return false
  }
  return true
}

function handleRegister(req, res) {
  readJsonBodyOr400(req, res).then((body) => {
    if (!body) return
    const { appId, appInstanceId, url, title, help } = body
    if (typeof appId !== 'string' || !appId) {
      return sendJson(res, 400, { ok: false, error: 'missing appId' })
    }
    if (typeof help !== 'string' || !help) {
      return sendJson(res, 400, { ok: false, error: 'missing help' })
    }
    // appInstanceId 必须由页面生成并随 register 提交（页面生命周期内固定，重连复用），
    // 服务器不代生成——避免服务器发新 id 导致旧实例残留名册
    if (typeof appInstanceId !== 'string' || !appInstanceId) {
      return sendJson(res, 400, { ok: false, error: 'missing appInstanceId (must be generated by the page)' })
    }
    const id = appInstanceId

    // upsert：同 id 重连（服务器重启丢名册后客户端沿用 id、或重复注册）→ 清旧状态再登记
    const isNew = !pages.has(id)
    dropPage(id)
    const now = Date.now()
    pages.set(id, {
      appId,
      url: typeof url === 'string' ? url : '',
      title: typeof title === 'string' ? title : '',
      help,
      connectedAt: now,
      lastSeen: now,
    })
    logger.info(`[BRIDGE] Instance registered: ${id} appId=${appId}${isNew ? '' : ' (upsert)'}\n`)
    sendJson(res, 200, { ok: true, appInstanceId: id })
  })
}

function handlePoll(req, res, id) {
  if (!checkAlive(id, Date.now())) {
    return sendJson(res, 404, { ok: false, error: 'unknown or offline appInstanceId' })
  }
  const page = pages.get(id)

  // 重复 poll：先兑现/清掉旧挂起（防页面重复开循环导致堆积）
  const old = pollPending.get(id)
  if (old) {
    clearTimeout(old.timer)
    pollPending.delete(id)
    try { old.res.destroy() } catch (e) {}
  }

  // 有积压消息 → 立即返回（一次可带多条）
  if ((outbox.get(id) || []).length > 0) {
    const messages = outbox.get(id)
    outbox.delete(id)
    page.lastSeen = Date.now()
    return sendJson(res, 200, { messages })
  }

  // 无消息 → 挂起，25s 空心跳
  const timer = setTimeout(() => {
    pollPending.delete(id)
    page.lastSeen = Date.now()
    sendJson(res, 200, { messages: [] })
  }, POLL_TIMEOUT_MS)
  pollPending.set(id, { res, timer })
  // 连接被对端断开（页面关闭/崩溃/断网）→ 页面已死，秒级出名册。
  // 仅当这条 poll 仍在挂起名单时才判死：正常路径（deliverToPoll/25s 到点/重复 poll）
  // 都先 pollPending.delete 再返回，close 之后触发时已不在名单中，自然豁免。
  // dropPage 会 clearTimeout，判死后 25s 定时器不会触发、不会给死人刷新 lastSeen。
  res.on('close', () => {
    const pending = pollPending.get(id)
    if (pending && pending.res === res) {
      logger.info(`[BRIDGE] Instance offline (closed): ${id} (appId=${page.appId})\n`)
      dropPage(id)
    }
  })
}

function handleReply(req, res) {
  readJsonBodyOr400(req, res).then((body) => {
    if (!body) return
    const msgId = body.id
    if (typeof msgId !== 'string' || !msgId) {
      return sendJson(res, 400, { ok: false, error: 'missing id' })
    }
    // 按 id 幂等：已兑现（超时/回包过）的 id 重复提交直接忽略
    settleSend(msgId, body)
    sendJson(res, 200, { ok: true })
  })
}

// 读原始二进制 body（artifact 上传用，不经 JSON 解析）；超过 maxBytes 断连并 reject
function readRawBody(req, maxBytes) {
  return new Promise((resolve, reject) => {
    let size = 0
    const chunks = []
    req.on('data', (chunk) => {
      size += chunk.length
      if (size > maxBytes) {
        req.pause() // 暂停接收，让 catch 分支能把 413 响应发出去再断连
        reject(new Error(`body too large (limit ${maxBytes} bytes)`))
        return
      }
      chunks.push(chunk)
    })
    req.on('end', () => resolve(Buffer.concat(chunks)))
    req.on('error', reject)
  })
}

// artifact 上传：实例须在线；原始字节落 JSL 条目；返回本地文件路径（AI 自行决定如何读取）
function handleArtifactUpload(req, res, id, url) {
  if (!checkAlive(id, Date.now())) {
    return sendJson(res, 404, { ok: false, error: 'unknown or offline appInstanceId' })
  }
  const limit = (artifacts.limits() || {}).maxBytes || 64 * 1024 * 1024
  const contentType = String(req.headers['content-type'] || '').split(';')[0].trim() || 'application/octet-stream'
  readRawBody(req, limit).then((buf) => {
    if (buf.length === 0) return sendJson(res, 400, { ok: false, error: 'empty body' })
    const name = url.searchParams.get('name') || 'artifact'
    const { artifactId, bytes, path } = artifacts.upload(id, name, contentType, buf)
    sendJson(res, 200, { ok: true, artifactId, bytes, path })
  }).catch((e) => {
    const tooLarge = e.message.startsWith('body too large')
    sendJson(res, tooLarge ? 413 : 400, { ok: false, error: e.message })
    if (tooLarge) req.destroy() // 响应送达后掐断仍在涌入的上传流
  })
}

// artifact 下载：按 artifactId（=JSL 条目文件名）取文件流
function handleArtifactDownload(res, artifactId) {
  const hit = artifacts.get(artifactId)
  if (!hit) return sendJson(res, 404, { ok: false, error: 'artifact expired or not found' })
  res.writeHead(200, {
    'Content-Type': hit.contentType,
    'Content-Length': hit.bytes,
    'Cache-Control': 'no-store',
    'access-control-allow-origin': '*',
  })
  fs.createReadStream(hit.file).pipe(res)
}

function handlePages(res) {
  const list = []
  const now = Date.now()
  for (const [id, page] of pages) {
    // 名册返回时顺带清掉已判死的条目
    if (!checkAlive(id, now)) continue
    list.push({
      appInstanceId: id,
      appId: page.appId,
      url: page.url,
      title: page.title,
      help: page.help,
      connectedAt: page.connectedAt,
      lastSeen: page.lastSeen,
      pendingMessages: (outbox.get(id) || []).length,
    })
  }
  sendJson(res, 200, list)
}

// 按 appId 聚合：AI 先看有哪些 App（含各自 help）再从 /pages 挑实例
function handleApps(res) {
  const apps = new Map() // appId → { appId, help, instances }
  const now = Date.now()
  for (const [id, page] of pages) {
    if (!checkAlive(id, now)) continue
    let app = apps.get(page.appId)
    if (!app) {
      app = { appId: page.appId, help: page.help, instances: 0 }
      apps.set(page.appId, app)
    }
    app.instances++
  }
  sendJson(res, 200, [...apps.values()])
}

function handleSend(req, res, id) {
  readJsonBodyOr400(req, res).then((body) => {
    if (!body) return
    if (!checkAlive(id, Date.now())) {
      return sendJson(res, 404, { ok: false, error: 'unknown or offline appInstanceId' })
    }
    if (body.type === undefined || body.type === null) {
      return sendJson(res, 400, { ok: false, error: 'missing type' })
    }
    let timeoutMs = SEND_DEFAULT_TIMEOUT_MS
    if (body.timeoutMs !== undefined) {
      if (typeof body.timeoutMs !== 'number' || body.timeoutMs <= 0 || body.timeoutMs > 300000) {
        return sendJson(res, 400, { ok: false, error: 'timeoutMs must be a number in (0, 300000]' })
      }
      timeoutMs = body.timeoutMs
    }
    const msgId = crypto.randomUUID()
    const queue = outbox.get(id)
    if (queue) queue.push({ id: msgId, type: body.type, payload: body.payload })
    else outbox.set(id, [{ id: msgId, type: body.type, payload: body.payload }])
    deliverToPoll(id)
    const timer = setTimeout(() => {
      // 超时：移除尚未送达的消息，避免 504 后页面还收到过期指令
      const q = outbox.get(id)
      if (q) {
        const i = q.findIndex(m => m.id === msgId)
        if (i !== -1) q.splice(i, 1)
        if (q.length === 0) outbox.delete(id)
      }
      sendPending.delete(msgId)
      sendJson(res, 504, { ok: false, id: msgId, error: 'reply timeout' })
    }, timeoutMs)
    sendPending.set(msgId, { res, timer, appInstanceId: id })
  })
}

async function serve(req, res, url) {
  const pathname = url.pathname
  const method = req.method

  if (pathname === '/bridge/api/register' && method === 'POST') return handleRegister(req, res)
  if (pathname === '/bridge/api/reply' && method === 'POST') return handleReply(req, res)
  if (pathname === '/bridge/api/pages' && method === 'GET') return handlePages(res)
  if (pathname === '/bridge/api/apps' && method === 'GET') return handleApps(res)
  if (pathname.startsWith('/bridge/api/poll/') && method === 'GET') {
    const id = pathname.slice('/bridge/api/poll/'.length)
    if (!id) return sendJson(res, 400, { ok: false, error: 'missing appInstanceId' })
    return handlePoll(req, res, id)
  }
  if (pathname.startsWith('/bridge/api/send/') && method === 'POST') {
    const id = pathname.slice('/bridge/api/send/'.length)
    if (!id) return sendJson(res, 400, { ok: false, error: 'missing appInstanceId' })
    return handleSend(req, res, id)
  }
  if (pathname === '/bridge/api/artifacts' && method === 'GET') return sendJson(res, 200, artifacts.stats())
  if (pathname === '/bridge/api/artifacts' && method === 'DELETE') return sendJson(res, 200, { ok: true, ...artifacts.clearAll() })
  if (pathname === '/bridge/api/artifacts/open' && method === 'POST') return sendJson(res, 200, artifacts.openDir())
  if (pathname.startsWith('/bridge/api/artifact/') && method === 'POST') {
    const id = pathname.slice('/bridge/api/artifact/'.length)
    if (!id) return sendJson(res, 400, { ok: false, error: 'missing appInstanceId' })
    return handleArtifactUpload(req, res, id, url)
  }
  if (pathname.startsWith('/bridge/api/artifact/') && method === 'GET') {
    const artifactId = decodeURIComponent(pathname.slice('/bridge/api/artifact/'.length))
    if (!artifacts.isValidArtifactId(artifactId)) return sendJson(res, 400, { ok: false, error: 'invalid artifactId' })
    return handleArtifactDownload(res, artifactId)
  }
  sendJson(res, 404, { ok: false, error: 'not found' })
}

// 只读统计（供 /status 状态页使用）：不修改任何状态
function counts() {
  let pendingCount = 0
  for (const queue of outbox.values()) pendingCount += queue.length
  const appIds = new Set()
  for (const p of pages.values()) appIds.add(p.appId)
  return {
    appCount: appIds.size,
    instanceCount: pages.size,
    pendingMessageCount: pendingCount,
    pendingPollCount: pollPending.size,
    pendingSendCount: sendPending.size,
  }
}

module.exports = { serve, counts }
